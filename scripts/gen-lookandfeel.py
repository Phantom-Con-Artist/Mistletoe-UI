def lock_screen():
    """kscreenlocker loads its UI from a Plasma *shell* package (kscreenlockerrc
    [Greeter] Theme), not from the Global Theme, so the Mistletoe lock screen
    ships as its own small shell package. Its colours follow the active
    scheme, so one package serves every edition."""
    shell = ROOT / "shells" / "org.mistletoe.lockscreen"
    lock = shell / "contents" / "lockscreen"
    lock.mkdir(parents=True, exist_ok=True)
    shared = ROOT / "plasma-widgets" / "shared"
    for src in sorted((ROOT / "lockscreen").glob("*.qml")) + [shared / "Shard.qml"]:
        (lock / src.name).write_text(src.read_text())
    # Defaults for what the bridge writes per machine, and the mark.
    (lock / "backdrop.js").write_text((ROOT / "lockscreen" / "backdrop.js").read_text())
    for stale in ("Glow.qml", "config.xml"):
        if (lock / stale).exists():
            (lock / stale).unlink()
    (lock / "mistletoe-mark.svg").write_text((ROOT / "branding" / "mistletoe-mark.svg").read_text())

    (shell / "metadata.json").write_text(json.dumps({
        # Registered as a Look-and-Feel package (see install.sh): as a plain
        # shell package kscreenlocker fell back to the distribution's.
        "KPackageStructure": "Plasma/LookAndFeel",
        # kscreenlocker rejects packages without API version 2 as "outdated".
        "X-Plasma-APIVersion": "2",
        "X-KDE-ParentApp": "org.kde.plasmashell",
        "KPlugin": {"Authors": [{"Name": "Subhradeep Sarkar"}], "Id": "org.mistletoe.lockscreen",
                    "Name": "Mistletoe Lock Screen", "License": "GPL-2.0-or-later",
                    "Description": "The Plasma Mistletoe lock screen", "Version": "0.1.0"},
    }, indent=4) + "\n")
    print("wrote", shell)


def main():
    for variant, cfg in VARIANTS.items():
        base = OUT / f"org.mistletoe.{variant}.desktop"
        contents = base / "contents"
        (contents / "layouts").mkdir(parents=True, exist_ok=True)
        (contents / "previews").mkdir(parents=True, exist_ok=True)
        (base / "metadata.json").write_text(json.dumps(metadata(variant, cfg), indent=4) + "\n")
        (contents / "defaults").write_text(DEFAULTS.format(
            scheme=cfg["scheme"], icons=cfg["icons"], variant=variant, wallpaper=cfg["wallpaper"],
            font10=FONT.format(size=10), font9=FONT.format(size=9), font8=FONT.format(size=8)))
        on_top = clock_on_top(cfg["wallpaper"], variant == "light")
        (contents / "layouts" / "org.kde.plasma.desktop-layout.js").write_text(
            LAYOUT.replace("%WALLPAPER%", cfg["wallpaper"]).replace("%CLOCK_ON_TOP%", "true" if on_top else "false"))
        # The splash and the leave screen, both built on the shared scene.
        colours = palette(cfg["scheme"])
        scene = SCENE.replace("%INK%", colours["ink"]).replace("%BONE%", colours["bone"]).replace("%GOLD%", colours["gold"])
        mark = (ROOT / "branding" / "mistletoe-mark.svg").read_text()
        for part, name, text in (("splash", "Splash.qml", SPLASH), ("logout", "Logout.qml", LOGOUT)):
            folder = contents / part
            folder.mkdir(parents=True, exist_ok=True)
            (folder / name).write_text(text)
            (folder / "MistletoeScene.qml").write_text(scene)
            (folder / "mistletoe-mark.svg").write_text(mark)
        stale = contents / "splash" / "images"
        if stale.exists():
            for f in stale.iterdir():
                f.unlink()
            stale.rmdir()
        print("wrote", base)


if __name__ == "__main__":
    main()
    lock_screen()
