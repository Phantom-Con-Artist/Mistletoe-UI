#!/usr/bin/env python3
"""Build an SDDM theme from the unchanged Mistletoe lock screen UI.

Bundle the user's current wallpaper, palette and fonts so the system greeter
does not need access to a home directory. Only backend bindings are adapted.
"""
import argparse
import configparser
import hashlib
import json
import os
import pwd
import re
import shutil
import subprocess
from pathlib import Path
from urllib.parse import unquote, urlparse

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
CONFIG = Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config"))
DATA = Path(os.environ.get("XDG_DATA_HOME", Path.home() / ".local/share"))


def read_config(path):
    config = configparser.ConfigParser(interpolation=None, strict=False)
    config.optionxform = str
    config.read(path)
    return config


def replace_once(text, old, new):
    if text.count(old) != 1:
        raise SystemExit(f"Lock screen backend changed; expected exactly one {old!r}")
    return text.replace(old, new, 1)


def adapt_ui():
    text = (ROOT / "lockscreen/LockScreenUi.qml").read_text()
    text = text.replace("import org.kde.plasma.private.sessions\n", "")
    text = text.replace("import org.kde.plasma.private.keyboardindicator as KeyboardIndicator\n", "")
    text = replace_once(text, "    id: ui\n", "    id: ui\n    required property var greeter\n")
    for prop in ("ink", "bone", "gold"):
        source = {"ink": "backgroundColor", "bone": "textColor", "gold": "focusColor"}[prop]
        text = replace_once(text, f"readonly property color {prop}: Kirigami.Theme.{source}",
                            f"readonly property color {prop}: greeter.{prop}")
    text = replace_once(text, "    SessionManagement {\n        id: session\n    }", """    QtObject {
        id: session
        readonly property bool canSuspend: ui.greeter.canSuspend
        readonly property bool canSwitchUser: true
        function suspend() { ui.greeter.suspend(); }
        function switchUser() { ui.greeter.chooseUser(); }
    }""")
    text = replace_once(text, "    KeyboardIndicator.KeyState {\n        id: capsLock\n        key: Qt.Key_CapsLock\n    }", """    QtObject {
        id: capsLock
        readonly property bool locked: ui.greeter.capsLocked
    }""")
    text = re.sub(r"\bauthenticator\b", "ui.greeter.authenticator", text)
    text = replace_once(text, "target: root", "target: ui.greeter")
    text = text.replace("kscreenlocker_userName", "ui.greeter.userLabel")
    text = text.replace('i18nd("plasma_shell_org.kde.plasma.desktop", "Unlocking failed")',
                        'qsTr("Unlocking failed")')
    text = re.sub(r"\bi18n\(", "qsTr(", text)
    for role in ("Display", "Accent", "Text"):
        text = text.replace(f'"Mistletoe {role}"', f"ui.greeter.{role.lower()}Font")
    text = replace_once(text, "enabled: !graceLock.running", "enabled: !graceLock.running && !ui.greeter.authenticator.busy")
    text = replace_once(text, "opacity: ui.active || password.text ? 1 : 0",
                        "opacity: !ui.greeter.selectingUser && (ui.active || password.text) ? 1 : 0")
    text = replace_once(text, "source: gemButton.modelData.icon",
                        'source: Qt.resolvedUrl("icons/" + gemButton.modelData.icon + ".svg")')
    return "// Generated by scripts/gen-sddm.py; presentation comes from lockscreen/LockScreenUi.qml.\n" + text


def wallpaper_path(override):
    if override:
        path = override
    else:
        config = read_config(CONFIG / "kscreenlockerrc")
        url = config.get("Greeter][Wallpaper][org.kde.image][General", "Image", fallback="")
        if not url:
            raise SystemExit("No lock screen wallpaper is configured; pass --wallpaper PATH")
        path = Path(unquote(urlparse(url).path))
    if path.is_dir():
        images = list((path / "contents/images").glob("*"))
        if not images:
            raise SystemExit(f"No images in wallpaper package {path}")
        path = max(images, key=lambda p: p.stat().st_size)
    if not path.is_file():
        raise SystemExit(f"Wallpaper does not exist: {path}")
    return path


def color(config, key, fallback):
    value = config.get("Colors:Window", key, fallback=fallback)
    if value.startswith("#"):
        return value
    components = [int(v) for v in value.split(",")]
    if len(components) != 3 or any(v < 0 or v > 255 for v in components):
        raise SystemExit(f"Invalid palette value {key}={value}")
    return "#" + "".join(f"{v:02x}" for v in components)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "build/sddm/mistletoe")
    parser.add_argument("--wallpaper", type=Path)
    parser.add_argument("--colors", type=Path, default=CONFIG / "kdeglobals")
    args = parser.parse_args()
    out = args.output.resolve()
    if out == ROOT or ROOT.is_relative_to(out):
        raise SystemExit("Output must be a dedicated theme directory")
    out.mkdir(parents=True, exist_ok=True)
    (out / "VERIFIED_SHA256").unlink(missing_ok=True)
    palette = read_config(args.colors)
    settings = {"ink": color(palette, "BackgroundNormal", "17,19,22"),
                "bone": color(palette, "ForegroundNormal", "233,228,214"),
                "gold": color(palette, "DecorationFocus", "212,172,112"),
                "defaultUser": pwd.getpwuid(os.getuid()).pw_name}
    shutil.copy2(ROOT / "sddm/Main.qml", out / "Main.qml")
    shutil.copy2(ROOT / "sddm/metadata.desktop", out / "metadata.desktop")
    shutil.copy2(ROOT / "plasma-widgets/shared/Shard.qml", out / "Shard.qml")
    shutil.copy2(ROOT / "branding/mistletoe-mark.svg", out / "mistletoe-mark.svg")
    (out / "LockScreenUi.qml").write_text(adapt_ui())
    (out / "theme.conf").write_text("[General]\niconTheme=breeze-dark\n")
    icons = out / "icons"
    icons.mkdir(exist_ok=True)
    icon_theme = read_config(CONFIG / "kdeglobals").get("Icons", "Theme", fallback="breeze-dark")
    for name in ("system-suspend", "system-switch-user"):
        candidates = [Path("/usr/share/icons") / theme / "actions/22" / (name + ".svg")
                      for theme in (icon_theme, "breeze-dark", "breeze")]
        source = next((p for p in candidates if p.is_file()), None)
        if source is None:
            raise SystemExit(f"The Breeze icon {name} is not installed")
        shutil.copy2(source, icons / (name + ".svg"))

    fonts = out / "fonts"
    fonts.mkdir(exist_ok=True)
    for role in ("Display", "Accent", "Text"):
        path = Path(subprocess.check_output(["fc-match", "-f", "%{file}", f"Mistletoe {role}"], text=True))
        if not path.is_file():
            raise SystemExit(f"Font role {role} cannot be resolved")
        dest = fonts / (role.lower() + path.suffix)
        shutil.copy2(path, dest)
        settings[role.lower() + "Font"] = str(dest.relative_to(out))

    Image.open(wallpaper_path(args.wallpaper)).convert("RGB").save(out / "wallpaper.png")
    installed = DATA / "plasma/shells/org.mistletoe.lockscreen/contents/lockscreen/backdrop.js"
    if installed.is_file() and not args.wallpaper:
        shutil.copy2(installed, out / "backdrop.js")
    else:
        im = ImageOps.fit(Image.open(out / "wallpaper.png").convert("L"), (1920, 1080))
        def light(box, veil):
            hist = im.crop(box).histogram()
            mean = sum(i * n for i, n in enumerate(hist)) / max(1, sum(hist)) / 255
            return mean * (1 - veil) + 0.05 * veil > 0.5
        info = dict(line.split("=", 1) for line in Path("/etc/os-release").read_text().splitlines() if "=" in line)
        distro = " ".join(info.get(k, "").strip('"') for k in ("NAME", "VERSION_ID")).strip()
        backdrop = {"clockOnLight": light((134, 324, 749, 648), 0.38),
                    "promptOnLight": light((750, 713, 1170, 753), 0.62),
                    "badgeOnLight": light((1380, 0, 1920, 86), 0.38), "distro": distro}
        (out / "backdrop.js").write_text(".pragma library\n" + "\n".join(
            f"var {key} = {json.dumps(value)};" for key, value in backdrop.items()) + "\n")
    (out / "settings.js").write_text(".pragma library\n" + "\n".join(
        f"var {key} = {json.dumps(value)};" for key, value in settings.items()) + "\n")
    (out / "SHA256SUMS").write_text("".join(
        f"{hashlib.sha256(path.read_bytes()).hexdigest()}  {path.relative_to(out)}\n"
        for path in sorted(out.rglob("*")) if path.is_file() and path.name != "SHA256SUMS"))
    print(f"Built {out}")


if __name__ == "__main__":
    main()
